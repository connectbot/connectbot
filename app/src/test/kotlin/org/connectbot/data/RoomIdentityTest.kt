package org.connectbot.data

import androidx.room.Database
import androidx.room.Entity
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.objectweb.asm.AnnotationVisitor
import org.objectweb.asm.ClassReader
import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.Opcodes
import org.objectweb.asm.Type
import org.robolectric.RobolectricTestRunner
import java.io.File
import java.util.UUID

@RunWith(RobolectricTestRunner::class)
class RoomIdentityTest {
    @Test
    fun everyRegisteredEntityHasOneUuidPrimaryKey() {
        // Room annotations have binary retention, so runtime reflection cannot read them.
        val declaration = annotationValues(ConnectBotDatabase::class.java, Database::class.java)
        val schema = JSONObject(File("schemas/${ConnectBotDatabase::class.java.name}/${declaration.getValue("version")}.json").readText())
            .getJSONObject("database")
        val entities = schema.getJSONArray("entities")
        val tables = (0 until entities.length()).associate {
            val entity = entities.getJSONObject(it)
            entity.getString("tableName") to entity
        }

        @Suppress("UNCHECKED_CAST")
        val registered = declaration.getValue("entities") as List<Type>
        assertTrue("The database must register entities", registered.isNotEmpty())
        val registeredTables = registered.map { type ->
            val entity = Class.forName(type.className)
            val table = (annotationValues(entity, Entity::class.java)["tableName"] as? String)
                ?.takeIf { it.isNotEmpty() } ?: entity.simpleName
            val definition = tables[table] ?: error("Missing exported Room schema for ${entity.name}")
            assertUuidPrimaryKey(entity, definition)
            // Also preserve the previous guard on identity references.
            generateSequence(entity) { it.superclass }.flatMap { it.declaredFields.asSequence() }
                .filter { it.name == "id" || it.name.endsWith("Id") }.forEach { field ->
                    assertEquals("${entity.name}.${field.name} must use UUID", UUID::class.java, field.type)
                }
            table
        }
        assertEquals("Every exported entity must be checked", tables.keys, registeredTables.toSet())
    }

    @Test
    fun rejectsNumericAndStringPrimaryKeysEvenWithoutAnIdProperty() {
        for (entity in listOf(NumericKey::class.java, StringKey::class.java)) {
            assertThrows(AssertionError::class.java) { assertUuidPrimaryKey(entity, definition()) }
        }
    }

    @Test
    fun acceptsUuidPrimaryKeyWithADifferentPropertyName() {
        assertUuidPrimaryKey(UuidKey::class.java, definition())
    }

    @Test
    fun rejectsCompositeAutogeneratedAndNullablePrimaryKeys() {
        val composite = definition().apply { getJSONObject("primaryKey").getJSONArray("columnNames").put("other") }
        val autogenerated = definition().apply { getJSONObject("primaryKey").put("autoGenerate", true) }
        val nullable = definition().apply { getJSONArray("fields").getJSONObject(0).put("notNull", false) }
        for (schema in listOf(composite, autogenerated, nullable)) {
            assertThrows(AssertionError::class.java) { assertUuidPrimaryKey(UuidKey::class.java, schema) }
        }
    }

    private fun assertUuidPrimaryKey(entity: Class<*>, definition: JSONObject) {
        val key = definition.getJSONObject("primaryKey")
        val columns = key.getJSONArray("columnNames")
        assertEquals("${entity.name} must have exactly one UUID primary key", 1, columns.length())
        assertFalse("${entity.name} must generate UUIDs before insertion", key.getBoolean("autoGenerate"))
        val fields = definition.getJSONArray("fields")
        val field = (0 until fields.length()).map { fields.getJSONObject(it) }
            .single { it.getString("columnName") == columns.getString(0) }
        assertTrue("${entity.name} primary key must be non-null", field.getBoolean("notNull"))
        assertEquals("${entity.name} UUID must be stored as TEXT", "TEXT", field.getString("affinity"))
        val path = field.getString("fieldPath")
        val type = path.split('.').fold(entity) { owner, property ->
            generateSequence(owner) { it.superclass }.mapNotNull { candidate ->
                candidate.declaredFields.firstOrNull { it.name == property }
            }.first().type
        }
        assertEquals("${entity.name}.$path must use UUID as its primary key", UUID::class.java, type)
    }

    private fun annotationValues(owner: Class<*>, annotation: Class<*>): Map<String, Any> {
        val values = mutableMapOf<String, Any>()
        var found = false
        owner.getResourceAsStream("/${owner.name.replace('.', '/')}.class")!!.use { stream ->
            ClassReader(stream).accept(
                object : ClassVisitor(Opcodes.ASM9) {
                    override fun visitAnnotation(descriptor: String, visible: Boolean): AnnotationVisitor? {
                        if (descriptor != Type.getDescriptor(annotation)) return null
                        found = true
                        return object : AnnotationVisitor(Opcodes.ASM9) {
                            override fun visit(name: String, value: Any) {
                                values[name] = value
                            }
                            override fun visitArray(name: String): AnnotationVisitor {
                                val items = mutableListOf<Any>()
                                values[name] = items
                                return object : AnnotationVisitor(Opcodes.ASM9) {
                                    override fun visit(name: String?, value: Any) {
                                        items.add(value)
                                    }
                                }
                            }
                        }
                    }
                },
                ClassReader.SKIP_CODE or ClassReader.SKIP_DEBUG or ClassReader.SKIP_FRAMES,
            )
        }
        assertTrue("${owner.name} must declare @${annotation.simpleName}", found)
        return values
    }

    private fun definition() = JSONObject(
        """{"primaryKey":{"columnNames":["key"],"autoGenerate":false},
            "fields":[{"columnName":"key","fieldPath":"key","affinity":"TEXT","notNull":true}]}""",
    )

    private class NumericKey(val key: Long)
    private class StringKey(val key: String)
    private class UuidKey(val key: UUID)
}
